// Visit rows (`medical_visit_json` and friends) -> domain types. Pure: no client, no Vue.
import type {
  BillableVisit,
  BillableVisitRow,
  MedicalQueue,
  MedicalVisit,
  MedicalVisitDetail,
  Prescription,
  PrescriptionRow,
  VisitDetailRow,
  VisitRow,
} from "@bongcun/core/medical";

type QueueRow = { date: string; counts: { scheduled: number; waiting: number; in_progress: number; done: number }; rows?: VisitRow[] | null };

export const toMedicalVisit = (row: VisitRow): MedicalVisit => ({
  id: row.id,
  code: row.code,
  branchId: row.branch_id,
  status: row.status,
  priority: row.priority,
  queueNo: row.queue_no ?? null,
  scheduledAt: row.scheduled_at ?? null,
  checkedInAt: row.checked_in_at ?? null,
  startedAt: row.started_at ?? null,
  signedAt: row.signed_at ?? null,
  createdAt: row.created_at,
  petId: row.pet_id,
  petName: row.pet_name,
  petPhotoUrl: row.pet_photo_url ?? null,
  speciesName: row.species_name ?? null,
  customerId: row.customer_id,
  customerName: row.customer_name,
  customerPhone: row.customer_phone,
  reason: row.reason ?? null,
  vetId: row.vet_id ?? null,
  vetName: row.vet_name ?? null,
  weightKg: row.weight_kg ?? null,
  outcome: row.outcome ?? null,
  recheckOn: row.recheck_on ?? null,
  followUpOf: row.follow_up_of ?? null,
  diagnosesText: row.diagnoses_text ?? null,
  hasAllergy: row.has_allergy === true,
  hasBehavior: row.has_behavior === true,
  contagious: row.contagious === true,
  branchName: row.branch_name ?? null,
  ownerInstructions: row.owner_instructions ?? null,
  estTotal: row.est_total ?? 0,
});

export const toQueue = (row: QueueRow): MedicalQueue => ({
  date: row.date,
  counts: {
    scheduled: row.counts.scheduled,
    waiting: row.counts.waiting,
    inProgress: row.counts.in_progress,
    done: row.counts.done,
  },
  rows: (row.rows ?? []).map(toMedicalVisit),
});

export const toDetail = (row: VisitDetailRow): MedicalVisitDetail => ({
  ...toMedicalVisit(row),
  branchName: row.branch_name ?? "",
  source: row.source,
  subjective: row.subjective ?? null,
  objective: row.objective ?? null,
  assessment: row.assessment ?? null,
  plan: row.plan ?? null,
  temperatureC: row.temperature_c ?? null,
  heartRate: row.heart_rate ?? null,
  respRate: row.resp_rate ?? null,
  vitalsNote: row.vitals_note ?? null,
  signedByName: row.signed_by_name ?? null,
  cancelledAt: row.cancelled_at ?? null,
  cancelReason: row.cancel_reason ?? null,
  followUpCode: row.follow_up_code ?? null,
  recheckVisit: row.recheck_visit
    ? {
        id: row.recheck_visit.id,
        code: row.recheck_visit.code,
        scheduledAt: row.recheck_visit.scheduled_at ?? null,
        status: row.recheck_visit.status,
      }
    : null,
  pet: row.pet
    ? {
        id: row.pet.id,
        name: row.pet.name,
        speciesName: row.pet.species_name ?? "",
        breed: row.pet.breed ?? null,
        sex: row.pet.sex ?? null,
        neutered: row.pet.neutered ?? null,
        birthDate: row.pet.birth_date ?? null,
        allergies: row.pet.allergies ?? null,
        behaviorNotes: row.pet.behavior_notes ?? null,
        status: row.pet.status,
        photoUrl: row.pet.photo_url ?? null,
        lastWeightKg: row.pet.last_weight_kg ?? null,
      }
    : null,
  diagnoses: (row.diagnoses ?? []).map((item) => ({
    id: item.id,
    termId: item.term_id ?? null,
    name: item.name,
    isContagious: item.is_contagious,
    note: item.note ?? null,
  })),
  items: (row.items ?? []).map((item) => ({
    id: item.id,
    kind: item.kind,
    serviceId: item.service_id ?? null,
    productId: item.product_id ?? null,
    name: item.name,
    qty: item.qty,
    unitName: item.unit_name ?? null,
    unitPrice: item.unit_price,
    amount: item.amount,
    takeHome: item.take_home,
    dose: item.dose ?? null,
    frequency: item.frequency ?? null,
    days: item.days ?? null,
    route: item.route ?? null,
    instructions: item.instructions ?? null,
    autoAdded: item.auto_added,
    invoiceLineId: item.invoice_line_id ?? null,
    createdByName: item.created_by_name ?? null,
    createdAt: item.created_at,
  })),
  addenda: (row.addenda ?? []).map((item) => ({
    id: item.id,
    content: item.content,
    createdByName: item.created_by_name ?? null,
    createdAt: item.created_at,
  })),
});

export const toPrescription = (row: PrescriptionRow): Prescription => ({
  code: row.code,
  date: row.date,
  branchName: row.branch_name ?? "",
  petName: row.pet_name,
  speciesName: row.species_name ?? null,
  weightKg: row.weight_kg ?? null,
  customerName: row.customer_name,
  customerPhone: row.customer_phone,
  vetName: row.vet_name ?? null,
  signed: row.signed,
  ownerInstructions: row.owner_instructions ?? null,
  recheckOn: row.recheck_on ?? null,
  diagnoses: row.diagnoses ?? [],
  items: (row.items ?? []).map((item) => ({
    name: item.name,
    qty: item.qty,
    unitName: item.unit_name ?? null,
    dose: item.dose ?? null,
    frequency: item.frequency ?? null,
    days: item.days ?? null,
    route: item.route ?? null,
    instructions: item.instructions ?? null,
    external: item.external,
  })),
});

export const toBillableVisit = (row: BillableVisitRow): BillableVisit => ({
  visitId: row.visit_id,
  code: row.code,
  petName: row.pet_name,
  petPhotoUrl: row.pet_photo_url ?? null,
  total: row.total,
  items: row.items.map((item) => ({
    id: item.id,
    kind: item.kind,
    name: item.name,
    qty: item.qty,
    unitName: item.unit_name ?? null,
    unitPrice: item.unit_price,
    amount: item.amount,
  })),
});
