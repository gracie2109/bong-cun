// Turns a sync diff into one forward-only, idempotent data migration.
import { activeCounts } from "./checks.mjs";
import { chunks, jsonLit, lit } from "./sql.mjs";

const BATCH = 500;

const UNIT_COLUMNS = ["level", "unit_type", "official_code", "name", "full_name", "parent_code", "status", "effective_from", "effective_to"];
const GHN_COLUMNS = ["provider_environment", "provider_code", "provider_parent_code", "provider_name", "match_method", "verified_at", "active"];

const distinctClause = (table, columns) =>
  `where (${columns.map((c) => `${table}.${c}`).join(", ")}) is distinct from (${columns.map((c) => `excluded.${c}`).join(", ")})`;

const unitStatements = (codes, units, catalogId) =>
  chunks(codes, BATCH).map((batch) => {
    const rows = batch.map((code) => {
      const u = units[code];
      return `  (${[code, ...UNIT_COLUMNS.map((c) => u[c]), catalogId].map(lit).join(", ")})`;
    });
    return `insert into public.location_units (code, ${UNIT_COLUMNS.join(", ")}, catalog_id) values
${rows.join(",\n")}
on conflict (code) do update set
  ${[...UNIT_COLUMNS, "catalog_id"].map((c) => `${c} = excluded.${c}`).join(", ")}, updated_at = now()
${distinctClause("location_units", UNIT_COLUMNS)};`;
  });

const ghnStatements = (codes, ghn, catalogId) =>
  chunks(codes, BATCH).map((batch) => {
    const rows = batch.map((code) => {
      const g = ghn[code];
      const verified = g.verified_at ? `${lit(g.verified_at)}::timestamptz` : "null";
      const values = [code, "ghn", g.provider_model, g.provider_environment, g.provider_code, g.provider_parent_code, g.provider_name, g.match_method].map(lit);
      return `  (${values.join(", ")}, ${verified}, ${lit(g.active)}, ${lit(catalogId)})`;
    });
    return `insert into public.location_provider_codes
  (code, provider, provider_model, provider_environment, provider_code, provider_parent_code, provider_name, match_method, verified_at, active, catalog_id) values
${rows.join(",\n")}
on conflict (provider, provider_model, code) do update set
  ${[...GHN_COLUMNS, "catalog_id"].map((c) => `${c} = excluded.${c}`).join(", ")}
${distinctClause("location_provider_codes", GHN_COLUMNS)};`;
  });

const catalogStatements = (catalog, counts) => {
  const c = catalog;
  return [
    `insert into public.location_catalogs (id, source, source_ref, effective_on, extracted_at, checksum, record_counts)
values (${[c.id, c.source, c.source_ref, c.effective_on].map(lit).join(", ")}, ${c.extracted_at ? `${lit(c.extracted_at)}::timestamptz` : "null"}, ${lit(c.checksum)}, ${jsonLit(counts)})
on conflict (id) do update set record_counts = excluded.record_counts, checksum = excluded.checksum, synced_at = now();`,
    `update public.location_catalogs set is_current = false where is_current and id <> ${lit(c.id)};`,
    `update public.location_catalogs set is_current = true where id = ${lit(c.id)} and not is_current;`,
  ];
};

const verifyBlock = (counts) => `do $$
declare
  v_provinces int;
  v_communes  int;
  v_ghn       int;
begin
  select count(*) into v_provinces from public.location_units where level = 'province' and status = 'active';
  select count(*) into v_communes from public.location_units where level = 'commune' and status = 'active';
  select count(*) into v_ghn from public.location_provider_codes where active;
  if v_provinces <> ${counts.provinces} or v_communes <> ${counts.communes} or v_ghn <> ${counts.ghn} then
    raise exception 'location sync: expected % provinces, % communes, % GHN codes but found %, %, %',
      ${counts.provinces}, ${counts.communes}, ${counts.ghn}, v_provinces, v_communes, v_ghn;
  end if;
end;
$$;`;

/** @returns {{ sql: string, counts: object }} */
export const writeMigration = ({ catalog, nextUnits, nextGhn, diff }) => {
  const active = activeCounts(nextUnits);
  const counts = {
    provinces: active.provinces,
    communes: active.communes,
    retired: Object.values(nextUnits).filter((u) => u.status === "retired").length,
    ghn: Object.values(nextGhn).filter((g) => g.active).length,
  };
  const parts = [
    `-- Location cache sync: catalog ${catalog.id} (in force since ${catalog.effective_on}).
-- Generated by apps/web/scripts/location-sync (workflow "Location sync"); do not edit by hand.
-- ${diff.changedUnits.length} unit rows and ${diff.changedGhn.length} GHN code rows written; safe to run more than once.`,
    ...catalogStatements(catalog, counts),
    ...unitStatements(diff.changedUnits, nextUnits, catalog.id),
    ...ghnStatements(diff.changedGhn, nextGhn, catalog.id),
    verifyBlock(counts),
  ];
  return { sql: parts.join("\n\n") + "\n", counts };
};
